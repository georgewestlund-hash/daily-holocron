# Unit separator keeps field boundaries out of the content itself.
$SIG_SEP = [string][char]31
function Get-RecordSignature {
    param($R)
    return ($R.first5 + $SIG_SEP + $R.materials + $SIG_SEP + $R.objective + $SIG_SEP +
            (($R.lesson) -join "`n") + $SIG_SEP + (($R.study) -join "`n") + $SIG_SEP +
            (($R.homework) -join "`n") + $SIG_SEP + $R.due)
}

