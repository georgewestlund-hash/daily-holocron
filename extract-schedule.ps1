<#
  Keeping the sheet unlisted
  --------------------------
  This repository is public, and docs/ is served on GitHub Pages, so anything
  written into schedule.json or printed to the console is world-readable (Actions
  logs on a public repo included). The planning sheet is link-shared and holds
  the whole year's teacher-side planning, so its id is kept out of all four:

    * not in this script  -> supplied via $env:HOLOCRON_SHEET_ID (a repo
                             Actions variable in CI) or sheet-id.local
    * not in schedule.json -> the sources[] block records no id or URL
    * not in the console   -> only the last 4 characters are ever printed
    * not in CLAUDE.md

  This is obscurity, not access control: anyone who has the link can still open
  the sheet. It closes the realistic path - reading the id out of the public
  repo or the published JSON. For real protection the sheet would have to stop
  being link-shared, which means authenticating the fetch with a service
  account key held in Actions secrets.
#>
