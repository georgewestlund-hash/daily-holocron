<#
  extract-schedule.ps1

  Builds docs/data/schedule.json for the Daily Holocron board by joining two
  inputs:

    1. docs/data/rotation.json - the rotation skeleton. One slot per
       (period, date) carrying semester, cycle and lesson number. Committed;
       generated by tools/build-rotation.ps1 from the ROT_DAYS rule table in
       docs/index.html crossed with the day-type calendar.

    2. the planning Google Sheet, "Master Data" tab - lesson content keyed on
       (Semester, Cycle, Lesson #, Track). Downloaded as .xlsx on every run.

  Why the split
  -------------
  The sheet has no dates; the board needs one record per (period, date). The
  bridge is the per-period meeting pattern, which comes from the ROT_DAYS rule
  table in the board rather than from the sheet. Periods skip different
  rotation days, and the rotation label's parenthetical is NOT the meeting list
  (2026-08-17 is labelled "DAY 2 (F-C)" yet A and G are what meet). See
  tools/build-rotation.ps1 for the derivation and the checks behind it.

  Join model
  ----------
    rotation slot (period, date) -> (semester, cycle, lessonNumber, track)
                                 -> Master Data row -> the seven content fields

  Track: HP covers periods A, D and G (Honors, planned in lockstep); EP covers
  period E (ECP, paced separately).

  Field mapping (Master Data column -> record field)
  --------------------------------------------------
    E First 5    -> first5      H Lesson Plan -> lesson[]
    F Bring      -> materials   I Study       -> study[]
    G Lit. Focus -> objective   J Homework    -> homework[]
                                K Due         -> due
  Columns A-D are the join key: Semester, Cycle, Lesson #, Track.

  Multi-line cells become arrays for lesson/study/homework, which the board
  joins with newlines to render as separate bullets. The other four stay plain
  strings.

  Publication horizon (built, currently OFF)
  ------------------------------------------
  -PublishLeadDays withholds a cycle's content until today is within N days of
  its first meeting, so unfinished future planning stays out of a publicly
  served file. Withheld slots publish blank, exactly like an unplanned lesson.

  Default is 0 = off, because the board's URL is not shared with students or
  families. Turning it on costs the ability to page the board forward when
  prepping, which is a real loss with no audience to protect against. Set it to
  2 if that changes.

  Usage:  powershell -ExecutionPolicy Bypass -File extract-schedule.ps1
#>

param(
    # Site root. schedule.json is written to <SiteDir>/data/schedule.json.
    [string]$SiteDir = (Join-Path $PSScriptRoot 'docs'),
    # The planning sheet's id. Deliberately NOT hardcoded - see "Keeping the
    # sheet unlisted" below. Resolved from the environment or a local file.
    [string]$SheetId,
    [string]$MasterTab = 'Master Data',
    [string]$RotationPath,
    [int]$FallSchoolYear = 2026,
    # Publication horizon, in days before a cycle starts. Content for a cycle
    # further out than this publishes blank, keeping unfinished future planning
    # out of a file that is served publicly.
    #
    # DISABLED (0) by design: the board's URL is not shared with students or
    # families, so there is no audience to withhold drafts from, and a horizon
    # would cost the ability to page the board forward when prepping. Set it to
    # 2 (or 7) if the address is ever handed out. Verified working - see the
    # boundary test in CLAUDE.md.
    [int]$PublishLeadDays = 0,
    # Testing hook: pretend it is this date (yyyy-MM-dd) when applying the
    # horizon. Leave unset in normal use; the runner's UTC date is used then.
    [string]$Today
)

