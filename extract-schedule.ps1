if (-not (Test-Path $RotationPath)) {
    throw "Rotation skeleton not found at $RotationPath. Run tools/build-rotation.ps1 first."
}
$rotation = Get-Content $RotationPath -Raw -Encoding UTF8 | ConvertFrom-Json
