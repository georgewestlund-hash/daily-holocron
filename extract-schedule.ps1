# Google Sheets keeps hard line breaks inside a cell. They are the whole point
# of the multi-line fields, so split on them and drop only blank lines.
function Split-Lines {
    param([string]$Text)
    $out = @()
    if ($null -eq $Text) { return , $out }
    foreach ($line in ($Text -split "`r?`n")) {
        $t = $line.Trim()
        if ($t -ne '') { $out += $t }
    }
    return , $out
}

function Join-Text {
    param([string]$Text)
    return ((Split-Lines $Text) -join "`n")
}

# "BC7" -> "BC". Cell refs are letters+digits; only the letters identify the
# column. Rows are keyed by letter rather than by header text because Master
# Data has two columns headed "Lesson" - C is the lesson number, H is the
# lesson content - so a name-keyed lookup silently collides.
function Get-ColumnLetter {
    param([string]$CellRef)
    return ($CellRef -replace '[^A-Za-z]', '').ToUpper()
}

function Read-ZipEntryText {
    param($Archive, [string]$EntryName)
    $entry = $Archive.Entries | Where-Object { $_.FullName -eq $EntryName }
    if (-not $entry) { return $null }
    $stream = $entry.Open()
    try {
        $reader = New-Object System.IO.StreamReader($stream, [System.Text.Encoding]::UTF8)
        try { return $reader.ReadToEnd() } finally { $reader.Dispose() }
    } finally { $stream.Dispose() }
}

<#
  Reads one worksheet of an .xlsx. Returns a hashtable:
    headers = column letter -> header text from row 1
    rows    = list of hashtables, column letter -> cell text
  Blank cells are absent from the row hashtable rather than present-and-empty.
#>
function Read-XlsxTab {
    param([string]$XlsxPath, [string]$TabName)

    Add-Type -AssemblyName System.IO.Compression.FileSystem | Out-Null
    $zip = [System.IO.Compression.ZipFile]::OpenRead($XlsxPath)
    try {
        $main = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'
        $rel  = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'

        # workbook.xml names the tabs and points at them by relationship id;
        # workbook.xml.rels resolves those to worksheet parts.
        $wbXml = Read-ZipEntryText $zip 'xl/workbook.xml'
        if (-not $wbXml) { throw 'xl/workbook.xml missing - not a valid .xlsx' }
        $wb = [xml]$wbXml
        $wbNs = New-Object System.Xml.XmlNamespaceManager($wb.NameTable)
        $wbNs.AddNamespace('m', $main)
        $wbNs.AddNamespace('r', $rel)

        $sheetNode = $null
        $names = @()
        foreach ($s in $wb.SelectNodes('//m:sheets/m:sheet', $wbNs)) {
            $names += $s.GetAttribute('name')
            if ($s.GetAttribute('name') -eq $TabName) { $sheetNode = $s }
        }
        if (-not $sheetNode) {
            throw ("No tab named '{0}'. Tabs present: {1}" -f $TabName, ($names -join ', '))
        }
        $rid = $sheetNode.GetAttribute('id', $rel)

        $relsXml = Read-ZipEntryText $zip 'xl/_rels/workbook.xml.rels'
        $rels = [xml]$relsXml
        $target = $null
        foreach ($r in $rels.Relationships.Relationship) {
            if ($r.Id -eq $rid) { $target = $r.Target }
        }
        if (-not $target) { throw "Could not resolve relationship $rid for tab '$TabName'" }
        $target = $target -replace '^/xl/', ''
        $target = $target -replace '^\.\./', ''
        $entryName = 'xl/' + $target

        # Shared strings: most cell text lives here, indexed by the cell's value.
        $shared = @()
        $ssXml = Read-ZipEntryText $zip 'xl/sharedStrings.xml'
        if ($ssXml) {
            $ss = [xml]$ssXml
            $ssNs = New-Object System.Xml.XmlNamespaceManager($ss.NameTable)
            $ssNs.AddNamespace('m', $main)
            foreach ($si in $ss.SelectNodes('//m:si', $ssNs)) {
                # A styled cell is split into <r> runs; concatenating the <t>
                # nodes in document order rebuilds the text, newlines included.
                $parts = @()
                foreach ($t in $si.SelectNodes('.//m:t', $ssNs)) { $parts += $t.InnerText }
                $shared += ($parts -join '')
            }
        }

        $shXml = Read-ZipEntryText $zip $entryName
        if (-not $shXml) { throw "Worksheet part $entryName missing" }
        $sh = [xml]$shXml
        $shNs = New-Object System.Xml.XmlNamespaceManager($sh.NameTable)
        $shNs.AddNamespace('m', $main)

        # Pass 1: rows as column-index -> text maps.
        $rawRows = @()
        foreach ($row in $sh.SelectNodes('//m:sheetData/m:row', $shNs)) {
            $cells = @{}
            foreach ($c in $row.SelectNodes('m:c', $shNs)) {
                $ref = $c.GetAttribute('r')
                if (-not $ref) { continue }
                $type = $c.GetAttribute('t')
                $text = ''
                if ($type -eq 's') {
                    $vNode = $c.SelectSingleNode('m:v', $shNs)
                    if ($vNode) {
                        $idx = [int]$vNode.InnerText
                        if ($idx -ge 0 -and $idx -lt $shared.Count) { $text = $shared[$idx] }
                    }
                } elseif ($type -eq 'inlineStr') {
                    $isNode = $c.SelectSingleNode('m:is', $shNs)
                    if ($isNode) {
                        $parts = @()
                        foreach ($t in $isNode.SelectNodes('.//m:t', $shNs)) { $parts += $t.InnerText }
                        $text = ($parts -join '')
                    }
                } else {
                    # Numbers, and formula cells carrying a cached value.
                    $vNode = $c.SelectSingleNode('m:v', $shNs)
                    if ($vNode) { $text = $vNode.InnerText }
                }
                if ($text -ne '') { $cells[(Get-ColumnLetter $ref)] = $text }
            }
            $rawRows += , $cells
        }

        if ($rawRows.Count -lt 1) { return @{ headers = @{}; rows = @() } }

        $header = @{}
        foreach ($k in $rawRows[0].Keys) { $header[$k] = ([string]$rawRows[0][$k]).Trim() }

        $out = @()
        for ($i = 1; $i -lt $rawRows.Count; $i++) {
            if ($rawRows[$i].Keys.Count -gt 0) { $out += , $rawRows[$i] }
        }
        return @{ headers = $header; rows = $out }
    } finally {
        $zip.Dispose()
    }
}

